/* =========================================================
   PROJECT SETTINGS
========================================================= */

const INITIAL_PROJECTS = 6;

const LOAD_MORE_COUNT = 6;


/* =========================================================
   ELEMENTS
========================================================= */

const projectsGrid =
    document.getElementById("projectsGrid");

const loadMoreBtn =
    document.getElementById("loadMoreBtn");

const projectsCount =
    document.getElementById("projectsCount");

const filterButtons =
    document.querySelectorAll(".project-filter");


/* =========================================================
   STATE
========================================================= */

let activeFilter = "all";

let visibleCount = INITIAL_PROJECTS;


/* =========================================================
   GET FILTERED PROJECTS
========================================================= */

function getFilteredProjects() {

    if (activeFilter === "all") {

        return projects;

    }

    return projects.filter(
        project =>
            project.filter === activeFilter
    );

}


/* =========================================================
   RENDER PROJECTS
========================================================= */

function renderProjects() {

    const filteredProjects =
        getFilteredProjects();

    const visibleProjects =
        filteredProjects.slice(
            0,
            visibleCount
        );


    projectsGrid.innerHTML = "";


    /* no projects */

    if (!visibleProjects.length) {

        projectsGrid.innerHTML = `
            <div class="no-projects">
                No projects found.
            </div>
        `;

        loadMoreBtn.classList.add("hidden");

        projectsCount.textContent = "";

        return;
    }


    /* create cards */

    visibleProjects.forEach(
        (project, index) => {

            const card =
                document.createElement("article");

            card.className =
                "project-card";


            card.style.animationDelay =
                `${index * 50}ms`;


            const techHTML =
                project.tech
                    .map(
                        tech =>
                            `<span>${tech}</span>`
                    )
                    .join("");


            const galleryButton =
                project.gallery &&
                project.gallery.length
                    ? `
                        <button
                            class="project-action"
                            type="button"
                            data-gallery="${project.id}"
                        >
                            View Gallery
                            <i class="fa-regular fa-images"></i>
                        </button>
                    `
                    : `
                        <button
                            class="project-action"
                            type="button"
                            disabled
                        >
                            Gallery
                        </button>
                    `;


            const caseStudyButton =
                project.caseStudy
                    ? `
                        <a
                            href="project-details.html?id=${project.id}"
                            class="project-action primary"
                        >
                            View Case Study
                            <i class="fa-solid fa-arrow-up-right-from-square"></i>
                        </a>
                    `
                    : `
                        <button
                            class="project-action primary"
                            type="button"
                            data-gallery="${project.id}"
                        >
                            View Project
                            <i class="fa-solid fa-arrow-up-right-from-square"></i>
                        </button>
                    `;


            card.innerHTML = `

                <div class="project-card-image">

                    <a href="${project.liveLink}"><img
                        src="${project.image}"
                        alt="${project.title}"
                        loading="lazy"
                    ></a>

                    <span class="project-category">
                        ${project.category}
                    </span>

                </div>


                <div class="project-card-content">

                    <h3>
                       <a href="${project.liveLink}" title="View Live"> ${project.title}  <i class="fa-solid fa-arrow-up-right-from-square"></i></a>
                    </h3>

                    <p>
                        ${project.description}
                    </p>


                    <div class="project-tech">

                        ${techHTML}

                    </div>


                    <div class="project-actions">

                        ${caseStudyButton}

                        ${galleryButton}

                    </div>

                </div>

            `;


            projectsGrid.appendChild(card);

        }
    );


    /* count */

    projectsCount.textContent =
        `Showing ${visibleProjects.length} of ${filteredProjects.length} projects`;


    /* load more state */

    if (
        visibleCount >=
        filteredProjects.length
    ) {

        loadMoreBtn.classList.add("hidden");

    } else {

        loadMoreBtn.classList.remove("hidden");

    }

}


/* =========================================================
   LOAD MORE
========================================================= */

loadMoreBtn.addEventListener(
    "click",
    () => {

        visibleCount +=
            LOAD_MORE_COUNT;

        renderProjects();

    }
);


/* =========================================================
   FILTERS
========================================================= */

filterButtons.forEach(
    button => {

        button.addEventListener(
            "click",
            () => {

                filterButtons.forEach(
                    btn =>
                        btn.classList.remove(
                            "active"
                        )
                );


                button.classList.add("active");


                activeFilter =
                    button.dataset.filter;


                /*
                 * Start every filter from
                 * six projects.
                 */

                visibleCount =
                    INITIAL_PROJECTS;


                renderProjects();


                /*
                 * Smoothly return toward
                 * project heading.
                 */

                document
                    .querySelector(
                        ".project-filters"
                    )
                    .scrollIntoView({
                        behavior: "smooth",
                        block: "nearest"
                    });

            }
        );

    }
);


/* =========================================================
   GALLERY MODAL
========================================================= */

const projectModal =
    document.getElementById("projectModal");

const modalClose =
    document.getElementById("modalClose");

const modalTitle =
    document.getElementById("modalTitle");

const modalCategory =
    document.getElementById("modalCategory");

const modalImage =
    document.getElementById("modalImage");

const modalDescription =
    document.getElementById("modalDescription");

const modalTech =
    document.getElementById("modalTech");

const modalCounter =
    document.getElementById("modalCounter");

const galleryPrev =
    document.getElementById("galleryPrev");

const galleryNext =
    document.getElementById("galleryNext");


let currentGallery = [];

let currentGalleryIndex = 0;


/* =========================================================
   OPEN GALLERY
========================================================= */

function openGallery(project) {

    if (
        !project.gallery ||
        !project.gallery.length
    ) {
        return;
    }


    currentGallery =
        project.gallery;

    currentGalleryIndex = 0;


    modalTitle.textContent =
        project.title;


    modalCategory.textContent =
        project.category;


    modalDescription.textContent =
        project.description;


    modalTech.innerHTML =
        project.tech
            .map(
                tech =>
                    `<span>${tech}</span>`
            )
            .join("");


    updateGalleryImage();


    projectModal.classList.add("active");

    projectModal.setAttribute(
        "aria-hidden",
        "false"
    );


    document.body.style.overflow =
        "hidden";

}


/* =========================================================
   UPDATE GALLERY
========================================================= */

function updateGalleryImage() {

    if (!currentGallery.length) {
        return;
    }


    modalImage.style.opacity = "0";


    setTimeout(
        () => {

            modalImage.src =
                currentGallery[
                    currentGalleryIndex
                ];


            modalImage.alt =
                modalTitle.textContent;


            modalImage.style.opacity =
                "1";

        },
        120
    );


    const current =
        String(
            currentGalleryIndex + 1
        ).padStart(2, "0");


    const total =
        String(
            currentGallery.length
        ).padStart(2, "0");


    modalCounter.textContent =
        `${current} / ${total}`;


    /*
     * Hide arrows if only one image
     */

    if (
        currentGallery.length <= 1
    ) {

        galleryPrev.style.display =
            "none";

        galleryNext.style.display =
            "none";

    } else {

        galleryPrev.style.display =
            "flex";

        galleryNext.style.display =
            "flex";

    }

}


/* =========================================================
   NEXT IMAGE
========================================================= */

galleryNext.addEventListener(
    "click",
    () => {

        currentGalleryIndex++;

        if (
            currentGalleryIndex >=
            currentGallery.length
        ) {

            currentGalleryIndex = 0;

        }

        updateGalleryImage();

    }
);


/* =========================================================
   PREVIOUS IMAGE
========================================================= */

galleryPrev.addEventListener(
    "click",
    () => {

        currentGalleryIndex--;

        if (
            currentGalleryIndex < 0
        ) {

            currentGalleryIndex =
                currentGallery.length - 1;

        }

        updateGalleryImage();

    }
);


/* =========================================================
   CLOSE GALLERY
========================================================= */

function closeGallery() {

    projectModal.classList.remove(
        "active"
    );

    projectModal.setAttribute(
        "aria-hidden",
        "true"
    );

    document.body.style.overflow =
        "";

}


/* close button */

modalClose.addEventListener(
    "click",
    closeGallery
);


/* backdrop */

document
    .querySelector(".modal-backdrop")
    .addEventListener(
        "click",
        closeGallery
    );


/* escape key */

document.addEventListener(
    "keydown",
    event => {

        if (
            event.key === "Escape" &&
            projectModal.classList.contains(
                "active"
            )
        ) {

            closeGallery();

        }


        if (
            event.key === "ArrowRight" &&
            projectModal.classList.contains(
                "active"
            )
        ) {

            galleryNext.click();

        }


        if (
            event.key === "ArrowLeft" &&
            projectModal.classList.contains(
                "active"
            )
        ) {

            galleryPrev.click();

        }

    }
);


/* =========================================================
   GALLERY BUTTON EVENT DELEGATION
========================================================= */

projectsGrid.addEventListener(
    "click",
    event => {

        const galleryButton =
            event.target.closest(
                "[data-gallery]"
            );


        if (!galleryButton) {
            return;
        }


        const projectId =
            galleryButton.dataset.gallery;


        const project =
            projects.find(
                item =>
                    item.id === projectId
            );


        if (project) {

            openGallery(project);

        }

    }
);


/* =========================================================
   INITIAL RENDER
========================================================= */

renderProjects();